const assert = require("node:assert/strict");
const { readFileSync } = require("node:fs");
const { join } = require("node:path");
const { test } = require("node:test");

test("keeps header in a fixed viewport while conversation scrolls", () => {
	const css = readFileSync(join(__dirname, "../style.css"), "utf8");
	const html = readFileSync(join(__dirname, "../index.html"), "utf8");
	assert.match(css, /body\{[^}]*height:100vh;[^}]*overflow:hidden;/);
	assert.match(css, /main\{[^}]*margin:0 auto;[^}]*min-height:0;[^}]*overflow:hidden/);
	assert.match(css, /#conversation\{[^}]*flex:1;[^}]*min-height:0;[^}]*overflow:auto/);
	assert.match(css, /#composer\{[^}]*flex:none/);
	assert.match(html, /id="composer-warning" role="alert" hidden/);
	assert.match(css, /#composer-warning\[hidden\]\{display:none\}/);
	assert.match(css, /#workspace\{[^}]*display:flex;[^}]*overflow:hidden/);
	assert.match(css, /#recent-sidebar\[hidden\]\{display:none\}/);
	assert.match(css, /@media\(max-width:800px\)\{#recent-sidebar\{position:absolute;z-index:4;/);
	assert.match(html, /<aside id="recent-sidebar"/);
	assert.match(html, /id="sidebar-new"/);
	assert.match(html, /id="sessions"[^>]*disabled>All chats<\/button>/);
	assert.match(html, /id="settings-back"[^>]*aria-label="Back to chat"/);
	assert.doesNotMatch(html, /id="new"|id="agent-close"|id="agent-tabs"|id="chat-view-button"|id="settings-view-button"/);
	assert.match(html, /<nav class="settings-toc" aria-label="Settings sections">/);
	for (const [id, label] of [["appearance", "Appearance"], ["default-model", "Default model"], ["approval", "Agent approval"], ["skills", "Skills"], ["mcp", "MCP servers"]]) {
		assert.match(html, new RegExp(`href="#settings-${id}"[^>]*>${label}</a>`));
		assert.match(html, new RegExp(`<fieldset id="settings-${id}"[^>]*tabindex="-1"`));
	}
	assert.match(css, /\.settings-sticky\{position:sticky/);
	assert.match(css, /\.settings-toc a:focus-visible\{/);
	assert.match(html, /id="theme-system"[^>]*value="system"/);
	assert.match(html, /id="theme-light"[^>]*value="light"/);
	assert.match(html, /id="theme-dark"[^>]*value="dark"/);
	assert.match(html, /id="default-model-select"[^>]*disabled/);
	assert.match(html, /id="default-model-note"/);
	assert.match(html, /id="approval-mode-toggle"[^>]*type="checkbox"[^>]*disabled/);
	assert.match(html, /id="approval-mode-note"[^>]*>[^<]*not a sandbox/i);
	assert.ok(html.indexOf('src="theme.js"') < html.indexOf('href="style.css"'));
	assert.match(html, /id="status" class="sr-only" role="status"/);
	assert.equal((html.match(/role="status"/g) ?? []).length, 4);
	assert.match(html, /id="tool-activity-status" class="sr-only" role="status"/);
	assert.match(html, /id="recent-toggle"[^>]*aria-controls="recent-sidebar"[^>]*aria-label="Toggle recent sidebar"[^>]*><svg[^>]*aria-hidden="true"/);
	assert.match(css, /#recent-toggle\[hidden\],#panel-toggle\[hidden\]\{display:none\}/);
	assert.match(html, /id="panel-toggle"[^>]*aria-controls="context-panel"[^>]*aria-label="Toggle details sidebar"[^>]*><svg[^>]*aria-hidden="true"/);
	assert.doesNotMatch(html, />Details<\/button>/);
	assert.match(html, /id="panel-resizer" role="separator" tabindex="0"/);
	assert.match(html, /<aside id="context-panel"/);
	assert.doesNotMatch(html, /id="activity"/);
	assert.match(css, /#context-panel\[hidden\]\{display:none\}/);
	assert.match(css, /#context-panel\{[^}]*min-width:220px;[^}]*max-width:420px/);
	assert.match(css, /\.md-table-wrap\{[^}]*max-width:100%;[^}]*overflow-x:auto/);
	assert.match(css, /@media\(prefers-reduced-motion:reduce\)/);
	assert.match(css, /#recent-list button\.chat-running::after\{[^}]*animation:chat-running-pulse/);
	assert.match(css, /@media\(prefers-reduced-motion:reduce\)\{#recent-list button\.chat-running::after\{animation:none;opacity:1/);
	assert.match(css, /\.thinking-content:empty::before\{content:'Waiting for thinking text…'/);
	assert.match(css, /\.thinking-unavailable \.thinking-content:empty::before\{content:'Thinking text unavailable'/);
	assert.match(css, /#workspace\[hidden\],#settings-view\[hidden\]\{display:none\}/);
	assert.match(css, /:root\[data-theme=dark\]\{--accent:#FF6B35;/);
	assert.match(css, /\.theme-setting input,\.approval-setting input\{accent-color:var\(--accent\)\}/);
	assert.doesNotMatch(css, /#c20075|#480029|Archivo|RobotoMono/i);
	assert.match(css, /header,#recent-sidebar,#context-panel,#command-menu/);
	assert.match(css, /@media\(prefers-color-scheme:dark\)/);
	assert.match(css, /@media\(max-width:900px\)/);
	assert.doesNotMatch(css, /body\{[^}]*min-height:100vh/);
});
